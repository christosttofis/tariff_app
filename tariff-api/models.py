"""
SQLAlchemy ORM models.

Design notes
------------
- suppliers / profiles / tariffs / changelog are proper relational tables.
- regulated, dam_data, notices are single-row "config" tables (id always = 1).
- rates, discounts, months and dam arrays are stored as JSON text columns —
  the frontend calculation code already consumes them as plain JSON, so there
  is no benefit to normalising them further at this stage.
- tariffs.status ('draft'|'pending'|'approved'|'rejected') defaults to
  'approved' so that all imported legacy data is immediately visible to the
  customer calculator.  Approval workflow is a later phase.
"""

from sqlalchemy import Boolean, Column, Float, ForeignKey, Integer, String, Text

from database import Base


class Supplier(Base):
    __tablename__ = "suppliers"

    id = Column(Integer, primary_key=True, autoincrement=True)
    name = Column(String, unique=True, nullable=False, index=True)
    licence = Column(String, default="")
    address = Column(String, default="")
    website = Column(String, default="")
    email = Column(String, default="")
    tel = Column(String, default="")
    regulated = Column(Boolean, default=False)  # e.g. EAC — some charges (MDM) are fixed by CERA, not freely set


class Profile(Base):
    """Half-hourly load-shape profiles parsed from EAC CSV exports."""
    __tablename__ = "profiles"

    id = Column(String, primary_key=True)       # uid generated by the frontend
    name = Column(String, nullable=False)
    desc = Column(String, default="")
    # JSON: array of 12 month objects — {W:[48 floats], NW:[48 floats], hasW, hasNW}
    months = Column(Text, default="[]")
    covW = Column(Integer, default=0)           # months with working-day data
    covNW = Column(Integer, default=0)          # months with non-working-day data
    rows = Column(Integer, default=0)
    colCount = Column(Integer, default=0)


class Tariff(Base):
    __tablename__ = "tariffs"

    id = Column(String, primary_key=True)       # uid generated by the frontend
    name = Column(String, nullable=False)
    supplier = Column(String, nullable=False)
    contract = Column(String, nullable=False)   # Domestic | Commercial | Industrial
    voltage = Column(String, nullable=False)    # LV | MV | HV
    pricing = Column(String, nullable=False)    # Fixed | ToU | Dynamic | Variable

    standing = Column(Float, default=0.0)       # monthly standing charge €
    mdm = Column(Float, default=0.0)            # meter data management charge, € per invoice — used when mdmSource='custom'
    # global   = use the CERA-set regulated MDM rate (Regulated tab); forced for regulated suppliers (e.g. EAC)
    # custom   = use this tariff's own `mdm` value — the default for non-regulated suppliers
    mdmSource = Column(String, default="custom")
    # MDM is charged once per invoice, not once per month — how often this
    # tariff invoices (1=monthly, 2=bimonthly) determines the annual total.
    # Set per tariff by the supplier since it follows their own billing cycle
    # (e.g. bimonthly for most domestic tariffs, monthly for industrial).
    mdmInvoiceMonths = Column(Integer, default=2)

    # JSON shape depends on pricing type:
    #   Fixed:    {rate}
    #   ToU:      {hiStart, hiEnd, hiPeakStart, hiPeakEnd, loPeakStart, loPeakEnd,
    #              hiPeakRate, hiOffRate, loPeakRate, loOffRate}
    #   Dynamic:  {mult, adder, damFloor}
    #   Variable: {resetMonths, tiers:[{upTo, rate, fixedCharge}]}
    rates = Column(Text, default="{}")

    profileId = Column(String, nullable=True)   # FK to profiles.id (unenforced)

    fpaSource = Column(String, default="global")  # global | custom | none
    fpaCustom = Column(Float, default=0.0)

    durationMonths = Column(Integer, nullable=True)  # null = indefinite
    loadEntitlement = Column(String, nullable=True)  # any | lt70 | gt70 | null

    # JSON: [{type:'standing'|'energy', percentage, durationMonths, conditions}]
    discounts = Column(Text, default="[]")

    vulnerable = Column(Boolean, default=False)

    # Approval workflow — not yet used in the UI, defaults to 'approved' so
    # all imported data is immediately visible to the customer calculator.
    status = Column(String, default="approved")  # draft | pending | approved | rejected
    rejection_reason = Column(String, nullable=True)

    createdAt = Column(String, nullable=True)   # ISO-8601 string
    updatedAt = Column(String, nullable=True)   # ISO-8601 string


class Regulated(Base):
    """Single-row table (id always 1). CERA-set regulated charges."""
    __tablename__ = "regulated"

    id = Column(Integer, primary_key=True, default=1)

    lv = Column(Float, default=0.0)     # LV grid usage €/kWh
    mv = Column(Float, default=0.0)     # MV grid usage €/kWh
    hv = Column(Float, default=0.0)     # HV grid usage €/kWh

    fpaLV = Column(Float, default=0.0)  # Fuel Price Adjustment — LV €/kWh
    fpaMV = Column(Float, default=0.0)  # Fuel Price Adjustment — MV €/kWh
    fpaHV = Column(Float, default=0.0)  # Fuel Price Adjustment — HV €/kWh

    pso = Column(Float, default=0.0)    # Public Service Obligation €/kWh
    res = Column(Float, default=0.0)    # RES & Energy Conservation Fund €/kWh
    mdm = Column(Float, default=0.0)    # Meter Data Management €/month

    updated_at = Column(String, nullable=True)            # ISO-8601 — max(grid_updated_at, universal_updated_at)
    fpa_updated_at = Column(String, nullable=True)        # ISO-8601 — set when fpaLV/fpaMV/fpaHV actually change value
    grid_updated_at = Column(String, nullable=True)       # ISO-8601 — set when lv/mv/hv actually change value
    universal_updated_at = Column(String, nullable=True)  # ISO-8601 — set when pso/res actually change value


class RegulatedHistory(Base):
    """One snapshot row per save of the Regulated Charges form — builds up a
    monthly/yearly trend history over time. Nothing existed before this feature
    shipped, so history only starts accumulating from here forward."""
    __tablename__ = "regulated_history"

    id = Column(Integer, primary_key=True, autoincrement=True)
    recorded_at = Column(String, nullable=False)  # ISO-8601

    lv = Column(Float, default=0.0)
    mv = Column(Float, default=0.0)
    hv = Column(Float, default=0.0)

    fpaLV = Column(Float, default=0.0)
    fpaMV = Column(Float, default=0.0)
    fpaHV = Column(Float, default=0.0)

    pso = Column(Float, default=0.0)
    res = Column(Float, default=0.0)
    mdm = Column(Float, default=0.0)


class DamData(Base):
    """Single-row table (id always 1). Day-Ahead Market price data."""
    __tablename__ = "dam_data"

    id = Column(Integer, primary_key=True, default=1)

    # JSON [null|float × 12]  — monthly average prices €/kWh
    damMonthly = Column(Text, default="[]")
    # JSON [[float × 48] × 12]  — half-hourly slot averages per month
    damBySlot = Column(Text, default="[]")
    # JSON [[{dateStr, dow, slots:[float×48]}...] × 12]  — raw daily data
    damDailyData = Column(Text, default="[]")

    damRowCount = Column(Integer, default=0)
    damYear = Column(Integer, default=2026)


class Notices(Base):
    """Single-row table (id always 1). HTML rich-text notices shown in calculator."""
    __tablename__ = "notices"

    id = Column(Integer, primary_key=True, default=1)
    assumptions_en = Column(Text, default="")
    assumptions_el = Column(Text, default="")
    legal_en = Column(Text, default="")
    legal_el = Column(Text, default="")
    vulnerable_en = Column(Text, default="")
    vulnerable_el = Column(Text, default="")


class SampleInvoiceConfig(Base):
    """Single-row table (id always 1). Admin on/off switch for the
    customer-facing sample invoice feature."""
    __tablename__ = "sample_invoice_config"

    id = Column(Integer, primary_key=True, default=1)
    enabled = Column(Boolean, default=False)


class Changelog(Base):
    """Audit log of tariff creates / updates / deletes."""
    __tablename__ = "changelog"

    id = Column(String, primary_key=True)       # uid
    tariffId = Column(String, nullable=True)
    tariffName = Column(String, nullable=True)
    supplier = Column(String, nullable=True)
    action = Column(String, nullable=False)     # created | updated | deleted
    # JSON: [{field, from, to}]
    changes = Column(Text, default="[]")
    ts = Column(String, nullable=True)          # ISO-8601 string
    actorRole = Column(String, nullable=True)   # admin | supplier — who made the change
    actorEmail = Column(String, nullable=True)


class TariffReport(Base):
    """Customer-submitted reports of erroneous tariff information — Article 121(ζ).
    tariffId/tariffName/supplier are null for a general site issue not tied to
    any one tariff (customer.html's footer "Report a general issue" link)."""
    __tablename__ = "tariff_reports"

    id = Column(String, primary_key=True)       # uid
    tariffId = Column(String, nullable=True)    # not FK-enforced, matches Changelog.tariffId
    tariffName = Column(String, nullable=True)  # snapshot at submission time
    supplier = Column(String, nullable=True)    # snapshot at submission time
    note = Column(Text, nullable=True)          # optional free text from reporter, max 2000 chars (enforced in schema)
    category = Column(String, default="other")  # incorrect_price | terms_mismatch | broken_link | other
    # Required at the API level (schemas.TariffReportIn) for every new
    # submission going forward — nullable here only because reports created
    # before this requirement existed have no reporterEmail to backfill.
    reporterEmail = Column(String, nullable=True)
    status = Column(String, default="open")     # open | reviewed | resolved | dismissed
    adminNote = Column(String, nullable=True)
    createdAt = Column(String, nullable=False)  # ISO-8601
    resolvedAt = Column(String, nullable=True)  # ISO-8601
    resolvedBy = Column(String, nullable=True)  # admin email
    ipAddress = Column(String, nullable=True)   # abuse tracing only, never serialized to any frontend


class PasswordReset(Base):
    """Single-use password reset tokens, valid for 1 hour."""
    __tablename__ = "password_resets"

    token = Column(String, primary_key=True)
    email = Column(String, nullable=False, index=True)
    expires_at = Column(String, nullable=False)  # ISO-8601
    used = Column(Boolean, default=False)


class TariffDocument(Base):
    """Uploaded supporting documents attached to a tariff submission."""
    __tablename__ = "tariff_documents"

    id = Column(Integer, primary_key=True, autoincrement=True)
    tariff_id = Column(String, nullable=False, index=True)
    original_name = Column(String, nullable=False)   # user-provided filename
    stored_name = Column(String, nullable=False, unique=True)  # uuid-based, safe
    uploaded_at = Column(String, nullable=False)     # ISO-8601
    uploaded_by = Column(String, nullable=False)     # uploader email


class OtpCode(Base):
    """Single-use 6-digit OTP codes for email 2FA, valid for 10 minutes."""
    __tablename__ = "otp_codes"

    id = Column(Integer, primary_key=True, autoincrement=True)
    email = Column(String, nullable=False, index=True)
    code = Column(String, nullable=False)
    expires_at = Column(String, nullable=False)  # ISO-8601
    created_at = Column(String, nullable=True)   # ISO-8601 — used for resend cooldown
    used = Column(Boolean, default=False)


class Message(Base):
    """Admin-authored broadcast messages sent to all or selected suppliers."""
    __tablename__ = "messages"

    id = Column(String, primary_key=True)           # uid
    subject = Column(String, nullable=False)
    body = Column(Text, nullable=False)              # plain text, newlines preserved
    audience = Column(String, nullable=False)        # all | selected
    target_suppliers = Column(Text, default="[]")    # JSON list of supplier names (audience='selected')
    created_by = Column(String, nullable=False)      # admin email
    created_at = Column(String, nullable=False)      # ISO-8601
    archived = Column(Boolean, default=False)        # hidden from suppliers, kept in admin history


class MessageRead(Base):
    """Tracks which supplier has read / acknowledged which message."""
    __tablename__ = "message_reads"

    id = Column(Integer, primary_key=True, autoincrement=True)
    message_id = Column(String, nullable=False, index=True)
    supplier_id = Column(Integer, ForeignKey("suppliers.id"), nullable=True, index=True)
    read_at = Column(String, nullable=False)          # ISO-8601
    acknowledged_at = Column(String, nullable=True)   # ISO-8601 — null until supplier acknowledges


class ScheduledNotification(Base):
    """Recurring notification rule — fires a new Message every N months."""
    __tablename__ = "scheduled_notifications"

    id = Column(String, primary_key=True)             # uid
    subject = Column(String, nullable=False)
    body = Column(Text, nullable=False)
    audience = Column(String, nullable=False)          # all | selected
    target_suppliers = Column(Text, default="[]")      # JSON list of supplier names (audience='selected')
    interval_months = Column(Integer, nullable=False)  # e.g. 6
    next_send_at = Column(String, nullable=False)      # ISO-8601 date — when it next fires
    enabled = Column(Boolean, default=True)
    created_by = Column(String, nullable=False)        # admin email
    created_at = Column(String, nullable=False)        # ISO-8601
    last_sent_at = Column(String, nullable=True)       # ISO-8601 — null until first fired


class User(Base):
    """Admin panel user accounts. Managed via create_user.py CLI."""
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, autoincrement=True)
    email = Column(String, unique=True, nullable=False, index=True)
    password_hash = Column(String, nullable=False)
    role = Column(String, nullable=False)           # admin | supplier
    # For supplier role: FK to suppliers.id. For admin role: null.
    supplier_id = Column(Integer, ForeignKey("suppliers.id"), nullable=True, index=True)
    is_active = Column(Boolean, default=True)
    created_at = Column(String, nullable=True)      # ISO-8601 string
    failed_attempts = Column(Integer, default=0)    # consecutive failed logins
    locked_until = Column(String, nullable=True)    # ISO-8601 — null means not locked
    otp_enabled = Column(Boolean, default=True)     # False skips the OTP step at login
    password_changed_at = Column(String, nullable=True)          # ISO-8601 — set on every password set
    must_change_password = Column(Boolean, default=False)        # forces the change-password gate
    password_expiry_notified_at = Column(String, nullable=True)  # ISO-8601 — guards the one-time reminder email


class LoginActivity(Base):
    """Audit log of login attempts (successful and failed), for the admin activity view."""
    __tablename__ = "login_activity"

    id = Column(Integer, primary_key=True, autoincrement=True)
    email = Column(String, nullable=False, index=True)  # attempted email, even if unknown/inactive
    user_id = Column(Integer, ForeignKey("users.id"), nullable=True, index=True)
    success = Column(Boolean, nullable=False)
    reason = Column(String, nullable=True)          # e.g. "bad_password", "locked", "otp_required", "otp_verified"
    ip_address = Column(String, nullable=True)
    user_agent = Column(String, nullable=True)
    ts = Column(String, nullable=False, index=True)  # ISO-8601


class PasswordHistory(Base):
    """Previously-used password hashes per user, for reuse prevention."""
    __tablename__ = "password_history"

    id = Column(Integer, primary_key=True, autoincrement=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False, index=True)
    password_hash = Column(String, nullable=False)
    changed_at = Column(String, nullable=False)     # ISO-8601
